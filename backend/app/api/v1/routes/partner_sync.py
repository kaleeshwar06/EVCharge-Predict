"""API route for EVCharge-Opt Partner Sync and Status."""
from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, HTTPException, Query, Response, status
import httpx

from app.core.config import get_settings
from app.schemas.partner_sync import (
    PartnerFeedbackItem,
    PartnerSyncRequest,
    PartnerSyncResponse,
)
from app.services.partner_sync_service import PartnerSyncService

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/partner", tags=["partner"])


@router.post(
    "/sync",
    response_model=PartnerSyncResponse,
    summary="Execute EVCharge-Opt Partner Sync",
    description=(
        "Executes a verified end-to-end exchange with EVCharge-Opt: "
        "dispatches demand forecast, requests priority grid allocation, and submits allocation feedback. "
        "Returns the real HTTP response, allocation ID, feedback ID, and station allocation metrics."
    ),
)
async def sync_with_partner(request: PartnerSyncRequest) -> PartnerSyncResponse:
    try:
        service = PartnerSyncService()
        return await service.execute_sync(request)
    except Exception as err:
        logger.exception("Unexpected error during partner sync execution")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Partner synchronization failed: {str(err)}",
        )


@router.get(
    "/status",
    summary="Check EVCharge-Opt Connection Status",
    description="Probes the deployed EVCharge-Opt partner service to verify live connectivity.",
)
async def partner_status() -> Dict[str, Any]:
    settings = get_settings()
    base_url = settings.evcharge_opt_base_url.rstrip("/")
    probe_url = f"{base_url}/api/v1/integration/health"
    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            res = await client.get(probe_url)
            if res.status_code == 200:
                return {
                    "connected": True,
                    "partner_base_url": base_url,
                    "http_status": 200,
                    "partner_details": res.json(),
                }
            return {
                "connected": False,
                "partner_base_url": base_url,
                "http_status": res.status_code,
                "error": res.text[:200],
            }
    except Exception as exc:
        return {
            "connected": False,
            "partner_base_url": base_url,
            "error": str(exc),
        }


@router.get(
    "/feedback",
    response_model=List[PartnerFeedbackItem],
    summary="List EVCharge-Opt Partner Feedback Records",
    description="Retrieves the authoritative list of feedback records generated by EVCharge-Opt from its verified GET /api/v1/feedback API.",
)
@router.get(
    "/feedbacks",
    response_model=List[PartnerFeedbackItem],
    include_in_schema=False,
)
async def list_partner_feedbacks(
    limit: int = Query(50, ge=1, le=100, description="Maximum records to retrieve")
) -> List[PartnerFeedbackItem]:
    service = PartnerSyncService()
    raw_feedbacks = await service.get_partner_feedbacks(limit=limit)
    return [PartnerFeedbackItem(**item) for item in raw_feedbacks]


@router.get(
    "/feedback/{feedback_id}",
    response_model=PartnerFeedbackItem,
    summary="Get EVCharge-Opt Partner Feedback by ID",
    description="Retrieves a specific feedback record generated by EVCharge-Opt by its identifier.",
)
@router.get(
    "/feedbacks/{feedback_id}",
    response_model=PartnerFeedbackItem,
    include_in_schema=False,
)
async def get_partner_feedback(feedback_id: str) -> PartnerFeedbackItem:
    service = PartnerSyncService()
    record = await service.get_partner_feedback_by_id(feedback_id)
    if not record:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Partner feedback '{feedback_id}' not found.",
        )
    return PartnerFeedbackItem(**record)


@router.post(
    "/feedback",
    summary="Receive Ingested Feedback from EVCharge-Opt",
    description="Endpoint for receiving post-optimization feedback from EVCharge-Opt, supporting idempotency keys.",
)
async def receive_partner_feedback(
    payload: Dict[str, Any],
    response: Response,
) -> Dict[str, Any]:
    service = PartnerSyncService()
    result = await service.save_partner_feedback(payload)
    if result.get("is_duplicate"):
        response.status_code = status.HTTP_200_OK
    else:
        response.status_code = status.HTTP_201_CREATED
    return result
